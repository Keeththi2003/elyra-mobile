package com.keeththigan.elyra.core.designsystem.dimensions

import androidx.compose.ui.unit.dp

/**
 * Elyra Design System
 *
 * Standard dimensions for reusable UI components.
 *
 * Spacing controls distance between elements.
 * Dimensions control the actual size of elements.
 */
object ElyraDimensions {

    // ============================================================
    // TOP APP BAR
    // ============================================================

    /**
     * Standard application top bar height.
     */
    val topBarHeight = 64.dp

    /**
     * Compact top bar height.
     */
    val topBarHeightCompact = 56.dp


    // ============================================================
    // BOTTOM NAVIGATION
    // ============================================================

    /**
     * Standard bottom navigation height.
     */
    val bottomNavigationHeight = 80.dp


    // ============================================================
    // BUTTONS
    // ============================================================

    /**
     * Standard primary button height.
     */
    val buttonHeight = 52.dp

    /**
     * Compact button height.
     */
    val buttonHeightSmall = 44.dp

    /**
     * Large prominent action button.
     */
    val buttonHeightLarge = 56.dp


    // ============================================================
    // INPUTS
    // ============================================================

    /**
     * Standard text field height.
     */
    val inputHeight = 56.dp

    /**
     * Compact input height.
     */
    val inputHeightSmall = 48.dp


    // ============================================================
    // ICONS
    // ============================================================

    /**
     * Standard icon size.
     */
    val iconSmall = 18.dp

    /**
     * Standard application icon size.
     */
    val iconMedium = 24.dp

    /**
     * Large icon.
     */
    val iconLarge = 32.dp

    /**
     * Extra large feature icon.
     */
    val iconExtraLarge = 48.dp


    // ============================================================
    // ICON BUTTONS
    // ============================================================

    /**
     * Standard touch target.
     *
     * 48dp provides a comfortable interaction area.
     */
    val iconButtonSize = 48.dp

    /**
     * Compact icon button.
     */
    val iconButtonSizeSmall = 40.dp

    /**
     * Large icon button.
     */
    val iconButtonSizeLarge = 56.dp


    // ============================================================
    // AVATARS
    // ============================================================

    val avatarSmall = 32.dp

    val avatarMedium = 40.dp

    val avatarLarge = 56.dp

    val avatarExtraLarge = 80.dp


    // ============================================================
    // DEVICE UI
    // ============================================================

    /**
     * Standard device illustration/icon container.
     */
    val deviceIconContainer = 56.dp

    /**
     * Large device visual.
     */
    val deviceIconContainerLarge = 72.dp


    // ============================================================
    // DIVIDERS
    // ============================================================

    /**
     * Standard divider thickness.
     */
    val divider = 1.dp


    // ============================================================
    // PROGRESS / STATUS
    // ============================================================

    /**
     * Small status indicator.
     */
    val statusIndicator = 8.dp

    /**
     * Medium status indicator.
     */
    val statusIndicatorMedium = 10.dp

    /**
     * Large status indicator.
     */
    val statusIndicatorLarge = 12.dp


    // ============================================================
    // LOADING
    // ============================================================

    val progressIndicatorSmall = 20.dp

    val progressIndicatorMedium = 32.dp

    val progressIndicatorLarge = 48.dp
}